"""Proxy label mapping and ground truth loaders for SlopGate backtesting.

Maps maintainer closure outcomes and GitHub labels to canonical Q1 categories.
Follows: implementation-plan.md Phase 8 Step 2, architecture.md §6.8, §7.3.

LIMITATIONS OF PROXY LABELS:
Maintainer labels and closure states are imperfect proxies:
1. Maintainers do not label every issue (many are closed with no label).
2. 'not_planned' can signify either a low-effort issue, an out-of-scope idea, or an invalid report.
3. Closed unmerged PRs may represent out-of-scope features rather than low-effort slop.
Gold labels hand-annotated by humans provide the primary ground truth.
"""

from __future__ import annotations

import csv
import logging
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    import sqlite3

    from slopgate.models import Item

from slopgate.store.db import save_ground_truth, save_item

logger = logging.getLogger(__name__)


def map_item_to_proxy_label(item: Item) -> str:
    """Map GitHub maintainer metadata and outcome to a canonical Q1 category.

    Categories:
    - Issue: real_bug_report, feature_request, support_question,
             likely_duplicate, security_report, low_effort
    - PR:    ready_for_review, needs_work, out_of_scope, low_effort
    """
    raw = item.raw if isinstance(item.raw, dict) else {}
    raw_labels = raw.get("labels", [])
    label_names = [
        (lbl.get("name", "") if isinstance(lbl, dict) else str(lbl)).lower()
        for lbl in raw_labels
    ]
    title_lower = (item.title or "").lower()
    body_lower = (item.body or "").lower()
    state_reason = str(raw.get("state_reason") or "").lower()

    if item.type == "pull_request":
        # 1. Obvious rejected AI or low-effort PRs
        if any("rejected ai" in lbl for lbl in label_names):
            return "low_effort"
        if "[rejected ai]" in title_lower or "ai junk" in title_lower:
            return "low_effort"
        if "spam" in label_names or "invalid" in label_names:
            return "low_effort"

        # 2. Merged PRs are accepted and ready for review
        pr_info = raw.get("pull_request") or {}
        if pr_info.get("merged_at") or raw.get("merged"):
            return "ready_for_review"

        # 3. Unmerged closed PRs
        if any(term in body_lower for term in ("ai coding assistant", "generated by bot", "reportbot")):
            return "low_effort"
        if any("needs work" in lbl or "changes requested" in lbl for lbl in label_names):
            return "needs_work"

        # Flask maintenance mode / out of scope default for unmerged PRs
        return "out_of_scope"

    # Issue mapping
    # 1. Rejected AI or low effort
    if any("rejected ai" in lbl for lbl in label_names):
        return "low_effort"
    if "[rejected ai]" in title_lower or "spam" in title_lower or "ai junk" in title_lower:
        return "low_effort"
    if "spam" in label_names or "invalid" in label_names or "wontfix" in label_names:
        return "low_effort"
    if state_reason == "not_planned" and len(item.body or "") < 120:
        return "low_effort"

    # 2. Security report
    if any(s in lbl for lbl in label_names for s in ("security", "cve", "vulnerability")):
        return "security_report"
    if "vulnerability" in title_lower or "security advisory" in title_lower:
        return "security_report"

    # 3. Duplicate
    if any("duplicate" in lbl for lbl in label_names):
        return "likely_duplicate"
    if "duplicate of #" in body_lower:
        return "likely_duplicate"

    # 4. Support question
    if any("question" in lbl or "support" in lbl for lbl in label_names):
        return "support_question"
    if "how do i" in title_lower or "how to" in title_lower:
        return "support_question"

    # 5. Feature request
    if any("feature" in lbl or "enhancement" in lbl for lbl in label_names):
        return "feature_request"

    # 6. Real bug report (default for closed completed issues or docs fixes)
    return "real_bug_report"


def populate_proxy_ground_truth(
    conn: sqlite3.Connection,
    items: list[Item],
) -> int:
    """Populate ground_truth table with proxy labels derived from maintainer outcomes.

    Ensures each item is saved in the items table so foreign key constraints hold.
    Returns the number of proxy records inserted.
    """
    count = 0
    for item in items:
        # Save item if not already saved
        item_id = save_item(conn, item)
        proxy_label = map_item_to_proxy_label(item)
        save_ground_truth(conn, item_id=item_id, label=proxy_label, source="proxy")
        count += 1
    logger.info("Populated %d proxy ground truth labels in database.", count)
    return count


def load_gold_labels_from_csv(
    conn: sqlite3.Connection,
    csv_path: str | Path,
) -> int:
    """Load human-annotated gold labels from CSV into ground_truth table.

    Expected CSV columns: item_id (e.g. pallets/flask#6170), gold_label
    Only rows where gold_label is non-empty will be saved with source='gold'.
    Returns the count of gold labels loaded.
    """
    path = Path(csv_path)
    if not path.is_file():
        raise FileNotFoundError(f"Gold labels CSV not found at: {path}")

    loaded = 0
    with path.open("r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            gold_label = (row.get("gold_label") or "").strip()
            if not gold_label:
                continue

            item_key = (row.get("item_id") or "").strip()
            repo = (row.get("repo") or "").strip()
            number_str = (row.get("number") or "").strip()

            item_row = None
            if repo and number_str.isdigit():
                item_row = conn.execute(
                    "SELECT id FROM items WHERE repo = ? AND number = ?",
                    (repo, int(number_str)),
                ).fetchone()
            elif "#" in item_key:
                parts = item_key.split("#", 1)
                if len(parts) == 2 and parts[1].isdigit():
                    item_row = conn.execute(
                        "SELECT id FROM items WHERE repo = ? AND number = ?",
                        (parts[0], int(parts[1])),
                    ).fetchone()

            if item_row:
                item_id = int(item_row["id"])
                save_ground_truth(conn, item_id=item_id, label=gold_label, source="gold")
                loaded += 1
            else:
                logger.warning("Could not match item %s in database to load gold label.", item_key)

    logger.info("Loaded %d gold labels from %s.", loaded, path)
    return loaded
